-- Dominios de correo al registrarse: lista blanca nueva (allowed_domains) y ampliacion de la lista negra (banned_domains).
-- Si el dominio no esta en ninguna de las dos, se comprueba que su web responde 2xx (email_web_check); si no, entra solo en la
-- lista negra con motivo «auto: …» y la persona ve el aviso de email temporal. Gestion en /moderacion.php#dominios. Ver lib/mail.php.
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS allowed_domains (
    domain   VARCHAR(120) NOT NULL PRIMARY KEY,
    reason   VARCHAR(120) DEFAULT NULL,
    added_by INT UNSIGNED DEFAULT NULL,
    created  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
